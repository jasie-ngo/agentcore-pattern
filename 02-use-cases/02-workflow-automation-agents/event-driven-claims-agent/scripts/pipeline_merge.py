"""Merge the client-neutral pipeline base with one client's overlay into the config.yaml that ships in that client's image.

    base     app/04_hesta_member_email/core/pipeline.base.yaml   models, pinned defaults and shared variables: same for everyone
    overlay  clients/<client>/pipeline/pipeline.yaml             the client's package, agents, prompts, orchestration

The overlay may add variables and model aliases but may not redefine what the base owns, so a client can never change a pinned
model or the guardrail sentinel by accident. Everything an agent refers to must live in the client's own package (or the core):
an overlay that points at another client's package, or names another client anywhere in its text, is refused. That is the guard
against copy-pasting one client's pipeline into the next and shipping the first client's wording.

Used by scripts/assemble_client.py. Needs PyYAML (the standard library has no YAML parser).
"""

from __future__ import annotations

import copy
import re
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - depends on the interpreter
    yaml = None

OVERLAY_KEYS = {"package", "vars", "models", "agents", "orchestrations", "entry"}
REQUIRED_KEYS = ("package", "agents", "orchestrations", "entry")
_PACKAGE = re.compile(r"^[a-z][a-z0-9_]*$")
_LOCAL_PATH = re.compile(r"^\./([A-Za-z0-9_]+)/")
HEADER = (
    "# GENERATED by scripts/assemble_client.py from core/pipeline.base.yaml and this client's pipeline overlay.\n"
    "# Do not edit this file: edit the overlay and assemble again.\n\n"
)


class PipelineError(Exception):
    """A readable reason the pipeline could not be merged."""


def _need_yaml() -> None:
    if yaml is None:
        raise PipelineError("merging a pipeline needs PyYAML (pip install pyyaml); the standard library cannot read YAML.")


def read_yaml(path: Path) -> tuple[dict, str]:
    """The parsed mapping and the raw text of one YAML file."""
    _need_yaml()
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise PipelineError(f"{path} cannot be read: {exc}") from exc
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise PipelineError(f"{path} is not valid YAML: {exc}") from exc
    if not isinstance(data, dict):
        raise PipelineError(f"{path} must hold one YAML mapping")
    return data, text


def client_packages(app_dir: Path) -> list[str]:
    """Every client package beside core/: a folder with a factory.py that is not the core."""
    return sorted(d.name for d in app_dir.iterdir() if d.is_dir() and d.name != "core" and (d / "factory.py").is_file())


def merge_pipeline(base: dict, overlay: dict) -> dict:
    """The base with the overlay laid over it. Raises if the overlay is incomplete, has unknown keys or redefines the base."""
    unknown = sorted(set(overlay) - OVERLAY_KEYS)
    if unknown:
        raise PipelineError(f"the overlay has unknown key(s) {unknown}; allowed: {sorted(OVERLAY_KEYS)}")
    missing = [k for k in REQUIRED_KEYS if not overlay.get(k)]
    if missing:
        raise PipelineError(f"the overlay is missing {missing}")

    merged = copy.deepcopy(base)
    for section in ("vars", "models"):
        for name, value in (overlay.get(section) or {}).items():
            if name in merged.get(section, {}):
                raise PipelineError(f"the overlay redefines {section}.{name}, which the base owns")
            merged.setdefault(section, {})[name] = copy.deepcopy(value)
    for key in ("agents", "orchestrations", "entry"):
        merged[key] = copy.deepcopy(overlay[key])
    return merged


def validate_pipeline(merged: dict, *, package: str, app_dir: Path, overlay_text: str) -> None:
    """Everything that can be checked without building the agents. Raises with every problem found."""
    problems: list[str] = []

    if not isinstance(package, str) or not _PACKAGE.match(package) or package == "core":
        problems.append(f'"package" must be a lower-case Python package name other than "core", not {package!r}')
    elif not (app_dir / package / "factory.py").is_file():
        problems.append(f'"package" is {package!r} but {app_dir / package / "factory.py"} does not exist: write the client package first')

    others = [p for p in client_packages(app_dir) if p != package]
    for other in others:
        if other.lower() in overlay_text.lower():
            problems.append(f'the overlay mentions "{other}", another client\'s package: a copied prompt or path would ship their wording')

    models = merged.get("models", {})
    agents = merged.get("agents", {})
    if not isinstance(agents, dict) or not agents:
        problems.append('"agents" must be a mapping with at least one agent')
        agents = {}
    for name, agent in agents.items():
        if not isinstance(agent, dict):
            problems.append(f"agents.{name} must be a mapping")
            continue
        if "model_id" in agent:
            problems.append(f"agents.{name} sets model_id; choose a model by alias so the pinned defaults apply")
        if agent.get("model") not in models:
            problems.append(f"agents.{name}.model is {agent.get('model')!r}; the models are {sorted(models)}")
        refs = [("type", agent.get("type"))] + [("tools", t) for t in agent.get("tools") or []]
        for field, ref in refs:
            if ref is None:
                continue
            match = _LOCAL_PATH.match(str(ref))
            if not match or match.group(1) not in (package, "core"):
                problems.append(f"agents.{name}.{field} {ref!r} must be a ./{package}/... or ./core/... path")

    orchestrations = merged.get("orchestrations", {})
    if merged.get("entry") not in orchestrations:
        problems.append(f"entry {merged.get('entry')!r} is not one of the orchestrations {sorted(orchestrations)}")
    for oname, orch in orchestrations.items():
        if not isinstance(orch, dict):
            continue
        entry = orch.get("entry_name")
        if entry is not None and entry not in agents:
            problems.append(f"orchestrations.{oname}.entry_name {entry!r} is not an agent")
        for conn in orch.get("connections") or []:
            if isinstance(conn, dict) and conn.get("agent") not in agents:
                problems.append(f"orchestrations.{oname} connects {conn.get('agent')!r}, which is not an agent")

    if problems:
        raise PipelineError("the pipeline overlay is not valid:\n" + "\n".join(f" - {p}" for p in problems))


def dump_pipeline(merged: dict) -> str:
    """The merged mapping as YAML text, long prompts as readable block scalars. Proves it round-trips before returning."""
    _need_yaml()

    class _Dumper(yaml.SafeDumper):
        pass

    def _str(dumper, value):
        style = "|" if "\n" in value else None
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)

    _Dumper.add_representer(str, _str)
    text = yaml.dump(merged, Dumper=_Dumper, sort_keys=False, allow_unicode=True, default_flow_style=False, width=120)
    if yaml.safe_load(text) != merged:  # a block scalar that cannot keep a string's exact bytes must fall back, not corrupt a prompt
        raise PipelineError("internal error: the merged pipeline does not survive being written as YAML")
    return HEADER + text


def build_pipeline(base_path: Path, overlay_path: Path, app_dir: Path) -> tuple[str, str]:
    """(package, config.yaml text) for one client. Raises PipelineError with a readable reason."""
    base, _ = read_yaml(base_path)
    overlay, overlay_text = read_yaml(overlay_path)
    merged = merge_pipeline(base, overlay)
    package = overlay["package"]
    validate_pipeline(merged, package=package, app_dir=app_dir, overlay_text=overlay_text)
    return package, dump_pipeline(merged)
